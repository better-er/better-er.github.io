const folderSelect = document.getElementById('folderSelect');
const modeSelect = document.getElementById('modeSelect');
const gallery = document.getElementById('gallery');


function tryLoadSequential(imgEl, srcList, onSuccess, onFailure) {
    // srcList: URI（字符串）数组。按顺序尝试每个，直到加载成功为止。
    const filtered = (srcList || []).map(s => (typeof s === 'string' ? s.trim() : '')).filter(Boolean);
    let idx = 0;

    function attempt() {
        if (idx >= filtered.length) {
            if (onFailure) onFailure();
            return;
        }
        const s = filtered[idx++];
        // 在设置src之前分配处理程序
        imgEl.onerror = () => {
            // 尝试下一个
            attempt();
        };
        imgEl.onload = () => {
            // 成功
            imgEl.onerror = null;
            if (onSuccess) onSuccess(s);
        };
        // 触发加载
        imgEl.src = s;
    }

    attempt();
}

function renderGallery() {
    const folder = folderSelect.value;
    const mode = modeSelect.value;
    const images = imageMap[folder];

    gallery.innerHTML = '';
    gallery.classList.toggle('single-col', mode === 'all');

    if (mode === 'all') {
        gallery.style.width = '100vw';
        gallery.style.marginLeft = 'calc(-1 * ((100vw - 100%) / 2))';
        gallery.style.marginRight = '0';

        images.forEach((srcs, idx) => {
            // 规范化为数组
            if (!Array.isArray(srcs)) srcs = [srcs];

            const item = document.createElement('div');
            item.className = 'gallery-item';

            const num = document.createElement('div');
            num.className = 'img-number';
            num.textContent = (idx + 1).toString();
            item.appendChild(num);

            const img = document.createElement('img');
            img.alt = `${folder}_${idx + 1}`;
            img.style.transition = 'all 0.4s ease';
            item.appendChild(img);

            // 尝试顺序加载；成功后存储成功的URL
            tryLoadSequential(img, srcs, (successfulUrl) => {
                img.dataset.loadedSrc = successfulUrl;
                img.style.filter = 'none';
                img.style.background = 'transparent';
            }, () => {
                // 全部失败
                const failTip = document.createElement('div');
                failTip.className = 'thumb-tip';
                failTip.textContent = '图片加载失败';
                item.style.position = 'relative';
                item.appendChild(failTip);
            });

            // 点击时如果已加载则跳转到原图
            item.onclick = () => {
                const src = img.dataset.loadedSrc || img.src;
                if (src) location.href = src;
            };

            gallery.appendChild(item);
        });
    } else {
        gallery.style.width = '';
        gallery.style.marginLeft = '';
        gallery.style.marginRight = '';

        images.forEach((srcs, idx) => {
            if (!Array.isArray(srcs)) srcs = [srcs];

            const item = document.createElement('div');
            item.className = 'gallery-item';

            const img = document.createElement('img');
            img.alt = `${folder}_${idx + 1}`;
            img.setAttribute('data-srcs', JSON.stringify(srcs));
            img.src = '';
            img.style.filter = 'blur(8px)';
            img.style.background = '#f5f5f5';
            img.style.transition = 'all 0.4s ease';

            const tip = document.createElement('div');
            tip.className = 'thumb-tip';
            tip.textContent = '点击加载图片';
            item.style.position = 'relative';
            item.appendChild(img);
            item.appendChild(tip);

            let loaded = false;
            item.onclick = () => {
                // 防止在加载时重复尝试
                if (item.dataset.loading) return;

                if (!loaded) {
                    // 标记为正在加载
                    item.dataset.loading = '1';

                    // 立即显示加载状态
                    tip.textContent = '加载中...';

                    const list = (JSON.parse(img.getAttribute('data-srcs') || '[]') || []).map(s => (typeof s === 'string' ? s.trim() : '')).filter(Boolean);

                    tryLoadSequential(img, list, (successfulUrl) => {
                        // 成功时立即移除遮罩/模糊和提示
                        img.style.filter = 'none';
                        img.style.background = 'transparent';
                        if (tip && tip.parentNode) tip.parentNode.removeChild(tip);

                        loaded = true;
                        img.dataset.loadedSrc = successfulUrl;

                        // 清除加载标志
                        delete item.dataset.loading;

                        // 加载成功后自动跳转到原图
                        location.href = successfulUrl;
                    }, () => {
                        tip.textContent = '图片加载失败';
                        // 清除加载标志
                        delete item.dataset.loading;
                    });
                } else {
                    const src = img.dataset.loadedSrc || img.src;
                    if (src) location.href = src;
                }
            };

            gallery.appendChild(item);
        });
    }
}

folderSelect.onchange = renderGallery;
modeSelect.onchange = renderGallery;

renderGallery();
